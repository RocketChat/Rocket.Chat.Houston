import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';

import {
  RC_METRICS_ENV,
  RC_METRICS_SETTING,
  SERVICES,
  VOLUMES,
  bindPorts,
  dashboard,
  files,
  grafanaUrl,
  isMonitoringNote,
  notes,
  sd,
  services,
  volumes,
} from '../../src/lib/monitoring';

/** What earlier releases built for the same inputs, recorded. */
const RECORDED = JSON.parse(
  fs.readFileSync(path.join(__dirname, '..', 'fixtures', 'lib', 'monitoring.json'), 'utf8'),
) as {
  names: Record<string, unknown>;
  volumes: unknown;
  services: unknown;
  bound_ports: unknown;
  paths: string[];
  content_sha256: [string, string][];
  notes: string[];
};

const RC_SERVICES = ['rocketchat-1', 'rocketchat-2'];
const PROJECT = 'houston-demo';

describe('the compose half', () => {
  it('names the same services and volumes earlier releases do', () => {
    const recorded = RECORDED.names;
    expect(recorded.services).toEqual([...SERVICES]);
    expect(recorded.volumes).toEqual([...VOLUMES]);
    expect(recorded.setting).toBe(RC_METRICS_SETTING);
    expect(recorded.env).toBe(RC_METRICS_ENV);
  });

  it('declares the same named volumes earlier releases declare', () => {
    expect(RECORDED.volumes).toEqual(volumes());
  });

  it('builds the same service documents, including the images', () => {
    expect(RECORDED.services).toEqual(services());
  });

  it('binds only the services that publish a port', () => {
    expect(RECORDED.bound_ports).toEqual(bindPorts(services(), '127.0.0.1'));
    // The exporters publish nothing and must be left untouched.
    expect(bindPorts(services(), '127.0.0.1')['node-exporter']).not.toHaveProperty('ports');
  });
});

describe('the config files written into a workspace', () => {
  it('is the same list of paths, in the same order', () => {
    expect(files(RC_SERVICES, PROJECT).map(([p]) => p)).toEqual(RECORDED.paths);
  });

  it('writes byte-identical CONTENTS for every one of them', () => {
    // The six embedded YAML documents are transcriptions, which is exactly the kind of
    // thing that looks right and differs by one space of indentation. They were extracted
    // from earlier releases mechanically rather than retyped, and the sha256 of each file
    // those releases wrote, recorded, is what proves it.
    const recorded = RECORDED.content_sha256;
    const mine = files(RC_SERVICES, PROJECT).map(
      ([p, c]) => [p, createHash('sha256').update(c, 'utf8').digest('hex')] as const,
    );
    expect(mine.map(([p, h]) => [p, h])).toEqual(recorded);
  });

  it('scopes the OTel collector to THIS project, so it cannot ingest another', () => {
    // The collector reads the host docker socket. Without the project filter it would
    // ship every container's logs on the box, including a real deployment's.
    const otel = files(RC_SERVICES, PROJECT).find(([p]) => p.endsWith('otel/config.yaml'));
    expect(otel?.[1]).toContain(`labels["com.docker.compose.project"] == "${PROJECT}"`);
    expect(otel?.[1]).not.toContain('__PROJECT__');
  });

  it('ships what a container wrote BEFORE the collector started, not only what follows', () => {
    // `houston monitor` on a running workspace started the collector at the END of each log
    // (the filelog default), so Rocket.Chat's boot output never reached Loki: measured, 57
    // of 65 lines missing from the "Rocket.Chat Logs" dashboard.
    const otel = files(RC_SERVICES, PROJECT).find(([p]) => p.endsWith('otel/config.yaml'));
    expect(otel?.[1]).toMatch(/\n {10}start_at: beginning\n/u);
  });

  it('generates a scrape target per Rocket.Chat service, on the metrics port', () => {
    const targets = files(RC_SERVICES, PROJECT).find(([p]) => p.endsWith('rocketchat.yml'));
    expect(targets?.[1]).toContain('    - rocketchat-1:9458');
    expect(targets?.[1]).toContain('    - rocketchat-2:9458');
  });

  it('agrees with earlier releases about a single-instance workspace too', () => {
    const recorded =
      '# Generated by houston. Prometheus scrape targets (rocketchat).\n' +
      '- targets:\n' +
      '    - rocketchat:9458\n' +
      '  labels:\n' +
      '    job: rocketchat\n' +
      '    service: rocketchat\n';
    expect(recorded).toBe(sd(['rocketchat:9458'], 'rocketchat'));
  });

  it('reads the shipped dashboards through the package-data lookup', () => {
    // A bundler rewrites this lookup, which is a Grafana with an empty folder and no
    // error anybody sees.
    expect(() => dashboard('houston-logs.json')).not.toThrow();
    expect(JSON.parse(dashboard('houston-logs.json'))).toHaveProperty('uid', 'houston-logs');
  });
});

describe('the notes printed after attach', () => {
  it('are the same lines, in the same order, with the same ports', () => {
    expect(notes()).toEqual(RECORDED.notes);
  });
});

describe('Grafana public URL regression', () => {
  it('configures the HTTPS sub-path without changing loopback services', () => {
    expect(services('https://h/').grafana?.environment).toMatchObject({
      GF_SERVER_ROOT_URL: 'https://h/grafana/',
      GF_SERVER_SERVE_FROM_SUB_PATH: 'true',
      GF_SECURITY_ADMIN_PASSWORD: 'admin',
      GF_AUTH_ANONYMOUS_ORG_ROLE: 'Viewer',
    });
    expect(services('').grafana?.environment).not.toHaveProperty('GF_SERVER_ROOT_URL');
    expect(services('').grafana?.environment).not.toHaveProperty('GF_SERVER_SERVE_FROM_SUB_PATH');
  });
  it('puts the public URL in both the Grafana and Loki notes', () => {
    const result = notes('https://h/grafana');
    expect(result[0]).toBe('Grafana:    https://h/grafana  (admin/admin; anonymous view enabled)');
    expect(result.at(-1)).toContain('(https://h/grafana/d/houston-logs)');
    expect(result[1]).toContain('http://localhost:9090');
  });
});

describe('a second monitored workspace, on the ports it was given', () => {
  it('publishes Prometheus and Grafana there, and says so', () => {
    const svcs = services('', [9091, 5051]);
    expect(svcs.prometheus?.ports).toEqual(['9091:9090']);
    expect(svcs.grafana?.ports).toEqual(['5051:3000']);
    expect(grafanaUrl('', false, 5051)).toBe('http://localhost:5051');
    expect(grafanaUrl('', true, 5051)).toBe('http://localhost:5051/grafana');
    const lines = notes(grafanaUrl('', false, 5051), 9091);
    expect(lines[0]).toContain('http://localhost:5051');
    expect(lines[1]).toContain('http://localhost:9091');
    expect(lines.join('\n')).not.toMatch(/localhost:(9090|5050)\b/u);
  });

  it('recognises its notes, so detaching drops them rather than leaving a stale address', () => {
    // The line a second workspace's record holds, as written: matched only at 9090, it stayed
    // behind after `monitor --off`, and a re-attach added a second one.
    expect(
      isMonitoringNote(
        'Prometheus: http://localhost:9091  (Status -> Targets: rocketchat, mongodb, node-exporter)',
      ),
    ).toBe(true);
    for (const line of notes(grafanaUrl('', false, 5051), 9091)) {
      expect({ line, ours: isMonitoringNote(line) }).toEqual({ line, ours: true });
    }
    expect(isMonitoringNote('Prometheus: http://localhost:9091  (somebody else wrote this)')).toBe(
      false,
    );
  });
});

describe('the pure Grafana URL helper', () => {
  it.each([
    ['', false, 'http://localhost:5050'],
    ['https://h', false, 'http://localhost:5050'],
    ['', true, 'http://localhost:5050/grafana'],
    ['https://h/', true, 'https://h/grafana'],
  ] as const)('combines public URL %s and sub-path %s', (url, subPath, expected) => {
    expect(grafanaUrl(url, subPath)).toBe(expected);
  });
});
